-- Голосовой ввод тренировки (docs/voice.md). Звук и распознанный текст не хранятся.
-- Синонимы системных упражнений для словаря разбора. Название и короткое название берутся из exercise.
-- Один синоним не принадлежит двум упражнениям; на уровне основ слов это проверяет тест словаря.
CREATE TABLE sizylift.voice_exercise_alias (
    exercise_id uuid NOT NULL REFERENCES sizylift.exercise (id) ON DELETE CASCADE,
    alias       text NOT NULL CHECK (length(alias) BETWEEN 1 AND 100),
    PRIMARY KEY (exercise_id, alias)
);
CREATE UNIQUE INDEX voice_exercise_alias_text ON sizylift.voice_exercise_alias (lower(alias));

-- Личные синонимы: как пользователь назвал упражнение, когда заменил надиктованное. alias_key — основы
-- слов, по нему повтор заменяет прежнюю запись. Упражнение может быть своим, поэтому без внешнего ключа.
CREATE TABLE sizylift.voice_user_alias (
    user_id     uuid        NOT NULL REFERENCES sizylift.user_account (id) ON DELETE CASCADE,
    alias_key   text        NOT NULL CHECK (length(alias_key) BETWEEN 1 AND 200),
    alias       text        NOT NULL CHECK (length(alias) BETWEEN 1 AND 100),
    exercise_id uuid        NOT NULL,
    updated_at  timestamptz NOT NULL,
    PRIMARY KEY (user_id, alias_key)
);

-- Суточный лимит распознаваний на пользователя (UTC-сутки).
CREATE TABLE sizylift.voice_daily_usage (
    user_id    uuid    NOT NULL REFERENCES sizylift.user_account (id) ON DELETE CASCADE,
    usage_date date    NOT NULL,
    requests   integer NOT NULL CHECK (requests > 0),
    PRIMARY KEY (user_id, usage_date)
);

